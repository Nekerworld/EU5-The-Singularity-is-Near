"""Generate the first bounded Age VII historical flavour wave from reviewed data."""
import argparse
import json
import pdx


def build():
    data=json.loads((pdx.MOD_ROOT/'data/historical_events_wave1.json').read_text(encoding='utf-8'))
    if 'advance:' in json.dumps(data):
        raise ValueError('has_advance takes a bare advance ID, not an advance: scope')
    entries=[]
    for chain in data['chains']:
        for stage,row in enumerate(chain['stages']):
            entries.append(dict(row,chain=chain['id'],stage=stage,year=chain['start_year'],end_year=1900,gate=chain['gate']))
    for row in data['singles']:
        entries.append(dict(row,chain=row['id'],stage=0,paid=True,single=True,
                            a_en='Fund a limited independent review.',a_ko='제한된 독립 검토에 예산을 배정하라.',
                            b_en='Leave it to private initiative.',b_ko='민간의 자율에 맡겨라.'))
    labels={lang:{} for lang in ['english','korean']}
    events=['# GENERATED by tools/gen_historical_events_wave1.py. Per-country state, no global once-only flags.','namespace = tsin_history_wave1']
    # Stable IDs are stored in authoring data, never reassigned from sorted titles.
    ids=[row['event_id'] for row in entries]
    if len(set(ids))!=len(ids):raise ValueError('duplicate historical event id')
    for row in entries:
        eid=row['event_id'];name='tsin_history_wave1.'+str(eid);stage=row['stage'];prefix='tsin_hist1_'+row['chain']
        predicate=f'NOT = {{ has_variable = {prefix}_stage }}' if stage==0 else f'has_variable = {prefix}_stage var:{prefix}_stage = {stage}'
        follow=f'NOT = {{ has_variable = {prefix}_year }}' if stage==0 else f'current_year > var:{prefix}_year'
        finish=row.get('single') or stage==3
        next_stage=99 if finish else stage+1
        events += [f'''{name} = {{
    type = country_event
    title = {name}.title
    desc = {name}.desc
    outcome = neutral
    illustration_tags = {{ 10 = interior 10 = regular }}
    trigger = {{
        current_year >= {row['year']}
        current_year < {row['end_year']}
        current_age = age_7_industrialization
        NOT = {{ has_game_rule = tsin_historical_events_off }}
        {row['gate']}
        {predicate}
        {follow}
    }}
    immediate = {{
        set_variable = {{ name = {prefix}_year value = current_year }}
        set_variable = {{ name = {prefix}_stage value = {next_stage} }}
    }}
    option = {{
        name = {name}.a
        {'trigger = { gold >= tsin_gold_cost_2 }' if row['paid'] else ''}
        {'change_gold_effect = { scale = -2 }' if row['paid'] else ''}
        {'add_country_modifier = { modifier = tsin_history_verified_practice years = 3 mode = replace }' if finish else ''}
        ai_chance = {{ factor = 4 }}
    }}
    option = {{
        name = {name}.b
        set_variable = {{ name = {prefix}_stage value = 99 }}
        ai_chance = {{ factor = 1 }}
    }}
}}''']
        for lang,short in [('english','en'),('korean','ko')]:
            for key in ['title','desc','a','b']:
                labels[lang][name+'.'+key]=row[key+'_'+short]
    events='\n\n'.join(events)+'\n'
    candidates='\n'.join('        10 = tsin_history_wave1.'+str(eid) for eid in ids)
    actions=f'''# One normal draw; dense adds one independent draw, never a second stage of the same chain that year.
yearly_country_pulse = {{ on_actions = {{ tsin_history_wave1_normal tsin_history_wave1_dense }} }}
tsin_history_wave1_normal = {{
    trigger = {{ current_year >= 1837 current_year < 1900 current_age = age_7_industrialization NOT = {{ has_game_rule = tsin_historical_events_off }} any_owned_location = {{ NOT = {{ location_rank = location_rank:rural_settlement }} }} }}
    random_events = {{
{candidates}
        chance_to_happen = 100
    }}
}}
tsin_history_wave1_dense = {{
    trigger = {{ current_year >= 1837 current_year < 1900 current_age = age_7_industrialization has_game_rule = tsin_historical_events_dense any_owned_location = {{ NOT = {{ location_rank = location_rank:rural_settlement }} }} }}
    random_events = {{
{candidates}
        chance_to_happen = 100
    }}
}}
'''
    rules='''tsin_historical_events = {
    default = tsin_historical_events_normal
    tsin_historical_events_normal = { flag = flavour_rule }
    tsin_historical_events_dense = { flag = flavour_rule }
    tsin_historical_events_off = { flag = flavour_rule }
}
'''
    modifiers='''tsin_history_verified_practice = {
    game_data = { category = country }
    research_speed_modifier = 0.01
    country_cabinet_efficiency = 0.02
}
'''
    common={
        'tsin_historical_events':('TSIN additional historical events','TSIN 추가 역사 사건'),
        'tsin_historical_events_desc':('First historical wave: four local chains and eight short events. Uses a separate bounded yearly draw, not the original flavour budget.','첫 역사 사건 제작분: 지역 사건열 네 종류와 짧은 사건 여덟 종류입니다. 기존 풍미 예산과 분리된 제한적 연간 추첨을 사용합니다.'),
        'tsin_historical_events_normal':('Standard additional wave','기본 추가 사건'),
        'tsin_historical_events_normal_desc':('At most one eligible event per year from this wave. Existing TSIN events remain separate.','이 제작분에서 조건을 만족하는 사건을 연 최대 한 번 추첨합니다. 기존 TSIN 사건은 별도로 유지됩니다.'),
        'tsin_historical_events_dense':('Dense additional wave','고밀도 추가 사건'),
        'tsin_historical_events_dense_desc':('At most two draws per year. A chain cannot advance twice in the same year.','연 최대 두 번 추첨하며 같은 사건열은 한 해에 두 단계 진행하지 않습니다.'),
        'tsin_historical_events_off':('Disabled','끔'),
        'tsin_historical_events_off_desc':('Do not draw first-wave historical events. Past choices are retained.','첫 제작분의 역사 사건을 추첨하지 않습니다. 과거 선택은 유지됩니다.'),
        'STATIC_MODIFIER_NAME_tsin_history_verified_practice':('Verified public practices','검증된 공공 실무'),
        'STATIC_MODIFIER_DESC_tsin_history_verified_practice':('A modest temporary benefit from independent verification and common public procedures. Refreshes rather than stacks.','독립 검토와 공통 공공 절차에서 얻은 작은 임시 효과입니다. 중복 누적하지 않고 기간만 갱신합니다.'),
    }
    files={
        'in_game/events/tsin_history_wave1.txt':events,
        'in_game/common/on_action/tsin_history_wave1_on_actions.txt':actions,
        'main_menu/common/game_rules/tsin_history_wave1_rules.txt':rules,
        'main_menu/common/static_modifiers/tsin_history_wave1_modifiers.txt':modifiers,
    }
    for lang,index in [('english',0),('korean',1)]:
        labels[lang].update({k:v[index] for k,v in common.items()})
        files[f'main_menu/localization/{lang}/tsin_history_wave1_l_{lang}.yml']='l_'+lang+':\n'+'\n'.join(' '+k+': '+json.dumps(v,ensure_ascii=False) for k,v in labels[lang].items())+'\n'
    return {rel: '\n'.join(line.rstrip() for line in body.splitlines())+'\n' for rel,body in files.items()}


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args();bad=[]
    for rel,text in build().items():
        path=pdx.MOD_ROOT/rel
        if args.check:
            if not path.exists() or pdx.read_text(path)!=text:bad.append(rel)
        else:pdx.write_text_bom(path,text)
    print(f'Historical wave 1: {len(bad)} mismatches')
    for rel in bad:print(rel)
    return bool(bad)


if __name__=='__main__':raise SystemExit(main())
