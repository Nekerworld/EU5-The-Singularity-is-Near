FIELDS = ('lender','borrower','currency','currency_live','fx','principal','rate','maturity','next_coupon','period','missed','kind','maturity_mode','timer_origin')
_map_tmp = 0


def read(field):
    return f'"global_variable_map(tsin_fc_{field}|scope:tsin_contract_id)"'


def put(field, value):
    # Engine misreads value = { ... } as an event-target opener; stage script values first.
    global _map_tmp
    value = str(value).strip()
    if value.startswith('{'):
        _map_tmp += 1
        tmp = f'tsin_fc_map_tmp_{_map_tmp}'
        return (f'save_temporary_scope_value_as = {{ name = {tmp} value = {value} }} '
                f'add_to_global_variable_map = {{ name = tsin_fc_{field} key = scope:tsin_contract_id value = scope:{tmp} }}')
    return f'add_to_global_variable_map = {{ name = tsin_fc_{field} key = scope:tsin_contract_id value = {value} }}'


