def compat_files(source):
    from finance_ui import CREDIT, patch_credit
    credit_source = source / CREDIT
    if not credit_source.exists():
        credit_source = pdx.game_root() / CREDIT
    return {ECONOMY: NOTE + '# LOCAL ONLY: Glorp integration, do not upload workshop code.\n' + patch_economy(fix_maintenance_visibility(pdx.read_text(source / ECONOMY))),
            GLORP_TABS: NOTE + '# LOCAL ONLY: Glorp integration, do not upload workshop code.\n' + patch_tabs(pdx.read_text(source / GLORP_TABS)),
            CREDIT: NOTE + '# LOCAL ONLY: finance host, source credit controller retained.\n' + patch_credit(pdx.read_text(credit_source))}


def generate_compat(source, output):
    files = compat_files(source)
    for rel,text in files.items():
        pdx.write_text_bom(output / rel, text)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--glorp-source', type=Path)
    parser.add_argument('--compat-output', type=Path)
    args = parser.parse_args()
    groups = [(pdx.MOD_ROOT, build())]
    if bool(args.glorp_source) != bool(args.compat_output):
        parser.error('--glorp-source and --compat-output are required together')
    if args.glorp_source:
        groups.append((args.compat_output, compat_files(args.glorp_source)))
    bad = []
    for root,files in groups:
        for rel,text in files.items():
            if args.check:
                if not (root / rel).exists() or pdx.read_text(root / rel) != text:
                    bad.append(str(root / rel))
            else:
                pdx.write_text_bom(root / rel, text)
    print(f'{sum(len(f) for _,f in groups)} stock UI files; {len(bad)} mismatches')
    for name in bad: print(name)
    return bool(bad)


if __name__ == '__main__':
    raise SystemExit(main())
