"""Generate global RGO rank bonuses without altering the other rank rules.

The runtime currently has four native ranks. Cities with >=100k population
receive the planned large-city rate via a location auto modifier.
"""
from pathlib import Path
import argparse
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pdx

RANK_RGO = {'rural_settlement': 0.75, 'town': 0.50, 'city': 0.30, 'megalopolis': 0.0}
REL_RANKS = 'in_game/common/location_ranks/00_default.txt'
REL_LARGE = 'in_game/common/auto_modifiers/tsin_rgo_rank_balance.txt'


def rank_text(vanilla):
    result = vanilla
    for block in reversed(pdx.top_level_blocks(vanilla)):
        if block.key not in RANK_RGO:
            continue
        text = re.sub(r'(?m)^\s*local_max_rgo_size_modifier\s*=\s*[-\d.]+[^\n]*\n', '', block.text)
        value = RANK_RGO[block.key]
        if value:
            text, count = re.subn(r'(\brank_modifier\s*=\s*\{)',
                                 lambda m: m[1]+f'\n\t\tlocal_max_rgo_size_modifier = {value:.2f}', text, count=1)
            assert count == 1, block.key
        result = result[:block.start] + text + result[block.end:]
    return '# Generated by tools/gen_rgo_rank_balance.py. Other vanilla rank rules are preserved.\n' + result


def build():
    native = pdx.game_root() / REL_RANKS
    # Explicit native read: never use mod source/mirror redirection here.
    original = native.read_text(encoding='utf-8-sig')
    return {
        REL_RANKS: rank_text(original),
        REL_LARGE: '''# No scripted country/world pulse. The engine evaluates this local condition.
# Existing city ID is retained for buildings and saves; 100 = 100,000 people.
tsin_large_city_rgo_balance = {
	category = location
	type = location
	potential_trigger = {
		location_rank ?= location_rank:city
		population >= 100
	}
	local_max_rgo_size_modifier = -0.10
}
''',
        'main_menu/localization/korean/tsin_rgo_rank_balance_l_korean.yml': '''l_korean:
 AUTO_MODIFIER_NAME_tsin_large_city_rgo_balance: "대도시의 자원 기반"
 tsin_large_city_rgo_balance_desc: "인구 10만 이상인 도시의 등급별 RGO 규모 보너스를 +30%에서 +20%로 조정합니다. 광산도시 등 별도 보너스는 그대로 합산됩니다."
''',
        'main_menu/localization/english/tsin_rgo_rank_balance_l_english.yml': '''l_english:
 AUTO_MODIFIER_NAME_tsin_large_city_rgo_balance: "Large City Resource Base"
 tsin_large_city_rgo_balance_desc: "Cities with at least 100,000 people receive a +20% rank RGO size bonus instead of +30%. Separate mining-town and other modifiers still apply."
''',
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    failures = []
    outputs = build()
    for rel, text in outputs.items():
        path = pdx.MOD_ROOT / rel
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8-sig') != text:
                failures.append(rel)
        else:
            pdx.write_text_bom(path, text)
    for rel in failures:
        print('OUTDATED', rel)
    print(f'RGO rank balance: {len(outputs)} files, {len(failures)} differences')
    return bool(failures)


if __name__ == '__main__':
    raise SystemExit(main())
