"""Generate the industrial companies and their stock market (docs/corporations.md).

Outputs (do not edit by hand):
  in_game/common/decisions/tsin_company_decisions.txt          found one company / dissolve all
  in_game/common/script_values/tsin_company_generated_values.txt  count, building levels, company value, index
  in_game/common/scripted_effects/tsin_company_generated_effects.txt  founding, quarterly stock update, dissolve

A company is a permanent country modifier tsin_company_<c>. Founding picks a headquarters location (the owned
location with the most company building levels) and lists the stock at 100.
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DECISIONS = ROOT / "in_game/common/decisions/tsin_company_decisions.txt"
OUT_VALUES = ROOT / "in_game/common/script_values/tsin_company_generated_values.txt"
OUT_EFFECTS = ROOT / "in_game/common/scripted_effects/tsin_company_generated_effects.txt"

# key, required advance, illustration good, priced good, company buildings
COMPANIES = [
    ("steel", "tsin_bessemer_process_advance", "steel", "steel",
     ["steel_mill", "iron_mill", "tsin_automated_iron_mill"]),
    ("machinery", "tsin_machine_works_advance", "tsin_engines", "tsin_engines",
     ["tsin_machine_works"]),
    ("textile", "tsin_mechanized_textile_mill_advance", "cloth", "cloth",
     ["textile_mill", "tsin_mechanized_textile_mill", "fine_cloth_mill", "tsin_automated_fine_cloth_mill"]),
    ("chemical", "tsin_improved_fertilizer_advance", "tsin_fertilizer", "tsin_fertilizer",
     ["tsin_fertilizer_plant", "tsin_nitrogen_fixation_plant", "tsin_explosives_plant"]),
    ("railway", "tsin_railway_network_advance", "steel", "steel",
     ["tsin_railway_station"]),
    ("farm_machinery", "tsin_mechanical_reaper_advance", "tsin_farm_machinery", "tsin_farm_machinery",
     ["tsin_farm_machinery_works"]),
]
HISTORY = 8

HEADER = "# GENERATED by tools/gen_company_decisions.py - edit the generator, not this file.\n"

FOUND = """tsin_found_{c}_company_decision = {{
	decision_category = economy_decisions
	image = "gfx/interface/icons/trade_goods/illustrations/icon_goods_{image}.dds"

	potential = {{
		has_advance = {adv}
		NOT = {{ has_country_modifier = tsin_company_{c} }}
	}}

	allow = {{
		tsin_company_count < tsin_company_limit
		gold >= tsin_gold_cost_4
	}}

	ai_will_do = {{
		value = 50
	}}

	option = {{
		name = tsin_found_{c}_company_decision.a
		ai_chance = {{ value = 100 }}
		effect = {{
			change_gold_effect = {{ scale = -4 }}
			add_country_modifier = {{ modifier = tsin_company_{c} months = -1 }}
			tsin_found_company_{c}_effect = yes
		}}
	}}
}}
"""

DISSOLVE = """tsin_dissolve_companies_decision = {
	decision_category = economy_decisions
	image = "gfx/interface/icons/trade_goods/illustrations/icon_goods_steel.dds"

	potential = {
		tsin_company_count > 0
	}

	allow = {
		always = yes
	}

	ai_will_do = {
		value = 0
	}

	option = {
		name = tsin_dissolve_companies_decision.a
		ai_chance = { value = 100 }
		effect = {
			tsin_dissolve_all_companies_effect = yes
		}
	}
}
"""


def levels(buildings: list[str], fn: str) -> list[str]:
    first, *rest = buildings
    out = [f'\tvalue = "{fn}(building_type:{first})"' if fn.startswith("location")
           else f"\tvalue = {fn}:{first}"]
    for b in rest:
        out.append(f'\tadd = "{fn}(building_type:{b})"' if fn.startswith("location") else f"\tadd = {fn}:{b}")
    return out


def values() -> str:
    v = [HEADER, "# Country scope unless noted. Company list: tools/gen_company_decisions.py COMPANIES.", ""]
    v += ["tsin_company_count = {", "\tvalue = 0"]
    v += [f"\tif = {{ limit = {{ has_country_modifier = tsin_company_{c} }} add = 1 }}" for c, *_ in COMPANIES]
    v += ["}", ""]
    for c, _, _, _, bld in COMPANIES:
        v += [f"# location scope", f"tsin_location_company_levels_{c} = {{"] + levels(bld, "location_building_level") + ["}", ""]
        v += [f"tsin_company_levels_{c} = {{"] + levels(bld, "total_effective_building_levels") + ["}", ""]
        v += [f"# Company value = stock price x company building levels.", f"tsin_company_value_{c} = {{",
              "\tvalue = 0", "\tif = {",
              f"\t\tlimit = {{ has_country_modifier = tsin_company_{c} has_variable = tsin_stock_{c} }}",
              f"\t\tvalue = var:tsin_stock_{c}", f"\t\tmultiply = tsin_company_levels_{c}", "\t}", "}", ""]
    v += ["tsin_company_total_value = {", "\tvalue = 0"]
    v += [f"\tadd = tsin_company_value_{c}" for c, *_ in COMPANIES]
    v += ["}", ""]
    v += ["# Weight of each company in the national index: building levels + 1, so a company without buildings",
          "# still counts.", "tsin_stock_index_weight = {", "\tvalue = 0"]
    for c, *_ in COMPANIES:
        v += [f"\tif = {{ limit = {{ has_country_modifier = tsin_company_{c} has_variable = tsin_stock_{c} }} "
              f"add = {{ value = tsin_company_levels_{c} add = 1 }} }}"]
    v += ["}", ""]
    v += ["# National stock index: weighted mean of the stock prices.", "tsin_stock_index_value = {", "\tvalue = 0"]
    for c, *_ in COMPANIES:
        v += [f"\tif = {{ limit = {{ has_country_modifier = tsin_company_{c} has_variable = tsin_stock_{c} }} "
              f"add = {{ value = var:tsin_stock_{c} multiply = {{ value = tsin_company_levels_{c} add = 1 }} }} }}"]
    v += ["\tif = {", "\t\tlimit = { tsin_stock_index_weight > 0 }", "\t\tdivide = tsin_stock_index_weight", "\t}",
          "}", ""]
    v += [f"# Mean of the last {HISTORY} quarterly index values (missing slots are skipped).",
          "tsin_stock_index_history_mean = {", "\tvalue = 0"]
    for i in range(HISTORY):
        v += [f"\tif = {{ limit = {{ has_variable = tsin_index_h{i} }} add = var:tsin_index_h{i} }}"]
    v += ["\tif = {", "\t\tlimit = { tsin_stock_index_history_count > 0 }",
          "\t\tdivide = tsin_stock_index_history_count", "\t}", "}", ""]
    v += ["tsin_stock_index_history_count = {", "\tvalue = 0"]
    for i in range(HISTORY):
        v += [f"\tif = {{ limit = {{ has_variable = tsin_index_h{i} }} add = 1 }}"]
    v += ["}", ""]
    v += ["# Stock report (tsin_corporate.100): 0 when the company does not exist."]
    for c, *_ in COMPANIES:
        v += [f"tsin_stock_price_{c} = {{", "\tvalue = 0", "\tif = {",
              f"\t\tlimit = {{ has_country_modifier = tsin_company_{c} has_variable = tsin_stock_{c} }}",
              f"\t\tvalue = var:tsin_stock_{c}", "\t}", "}", ""]
    v += ["# location scope (tsin_corporations map mode): company building levels of the owner's companies.",
          "tsin_location_owner_company_levels = {", "\tvalue = 0"]
    for c, *_ in COMPANIES:
        v += [f"\tif = {{ limit = {{ owner ?= {{ has_country_modifier = tsin_company_{c} }} }} "
              f"add = tsin_location_company_levels_{c} }}"]
    v += ["}", ""]
    v += ["# location scope: 1 when the location is the headquarters of one of the owner's companies.",
          "tsin_location_company_hq = {", "\tvalue = 0"]
    for c, *_ in COMPANIES:
        v += ["\tif = {", "\t\tlimit = {", f"\t\t\towner ?= {{ has_variable = tsin_hq_{c} }}",
              f"\t\t\tthis = owner.var:tsin_hq_{c}", "\t\t}", "\t\tvalue = 1", "\t}"]
    v += ["}", ""]
    v += ["tsin_stock_index_report = {", "\tvalue = 0",
          "\tif = { limit = { has_variable = tsin_stock_index } value = var:tsin_stock_index }", "}", ""]
    v += ["tsin_world_stock_index_report = {", "\tvalue = 0",
          "\tif = { limit = { has_global_variable = tsin_world_stock_index } value = global_var:tsin_world_stock_index }",
          "}", ""]
    return "\n".join(v)


def effects() -> str:
    e = [HEADER, "# Country scope. Stock market model: docs/corporations.md.", ""]
    for c, _, _, good, _ in COMPANIES:
        e += [f"tsin_found_company_{c}_effect = {{",
              "\tordered_owned_location = {",
              f"\t\torder_by = tsin_location_company_levels_{c}",
              "\t\tmax = 1",
              f"\t\tsave_temporary_scope_as = tsin_company_hq",
              "\t}",
              "\tif = {",
              "\t\tlimit = { exists = scope:tsin_company_hq }",
              f"\t\tset_variable = {{ name = tsin_hq_{c} value = scope:tsin_company_hq }}",
              "\t}",
              f"\tset_variable = {{ name = tsin_stock_{c} value = 100 }}",
              "\tset_variable = tsin_has_stock_market",
              "}", ""]
        e += [f"tsin_update_stock_{c}_effect = {{",
              "\tif = {",
              f"\t\tlimit = {{ has_country_modifier = tsin_company_{c} has_variable = tsin_stock_{c} }}",
              "\t\tset_variable = { name = tsin_stock_up value = 0.5 }",
              "\t\tif = {",
              "\t\t\tlimit = {",
              "\t\t\t\texists = capital",
              f"\t\t\t\tcapital.market = {{ \"market_price(goods:{good})\" > {{ value = \"default_price(goods:{good})\" multiply = 1.3 }} }}",
              "\t\t\t}",
              "\t\t\tset_variable = { name = tsin_stock_up value = 0.7 }",
              "\t\t}",
              "\t\telse_if = {",
              "\t\t\tlimit = {",
              "\t\t\t\texists = capital",
              f"\t\t\t\tcapital.market = {{ \"market_price(goods:{good})\" > {{ value = \"default_price(goods:{good})\" multiply = 1.1 }} }}",
              "\t\t\t}",
              "\t\t\tset_variable = { name = tsin_stock_up value = 0.6 }",
              "\t\t}",
              "\t\telse_if = {",
              "\t\t\tlimit = {",
              "\t\t\t\texists = capital",
              f"\t\t\t\tcapital.market = {{ \"market_price(goods:{good})\" < {{ value = \"default_price(goods:{good})\" multiply = 0.7 }} }}",
              "\t\t\t}",
              "\t\t\tset_variable = { name = tsin_stock_up value = 0.3 }",
              "\t\t}",
              "\t\telse_if = {",
              "\t\t\tlimit = {",
              "\t\t\t\texists = capital",
              f"\t\t\t\tcapital.market = {{ \"market_price(goods:{good})\" < {{ value = \"default_price(goods:{good})\" multiply = 0.9 }} }}",
              "\t\t\t}",
              "\t\t\tset_variable = { name = tsin_stock_up value = 0.4 }",
              "\t\t}",
              f"\t\ttsin_stock_random_walk_effect = {{ STOCK = tsin_stock_{c} }}",
              "\t}",
              "}", ""]
    e += ["# Quarterly: every company stock, then the national index and its history.",
          "tsin_update_stocks_effect = {"]
    e += [f"\ttsin_update_stock_{c}_effect = yes" for c, *_ in COMPANIES]
    e += ["\ttsin_update_stock_index_effect = yes", "}", ""]
    e += ["# Companies founded before the stock market existed (older saves) get their headquarters and stock.",
          "tsin_init_existing_companies_effect = {"]
    for c, *_ in COMPANIES:
        e += ["\tif = {", f"\t\tlimit = {{ has_country_modifier = tsin_company_{c} NOT = {{ has_variable = tsin_stock_{c} }} }}",
              f"\t\ttsin_found_company_{c}_effect = yes", "\t}"]
    e += ["}", ""]
    e += ["# Market-wide shock: every stock times FACTOR, then the index is recomputed.",
          "tsin_scale_stocks_effect = {"]
    for c, *_ in COMPANIES:
        e += ["\tif = {", f"\t\tlimit = {{ has_variable = tsin_stock_{c} }}",
              f"\t\tchange_variable = {{ name = tsin_stock_{c} multiply = $FACTOR$ }}",
              f"\t\tclamp_variable = {{ name = tsin_stock_{c} min = 10 max = 1000 }}", "\t}"]
    e += ["\tif = {", "\t\tlimit = { has_variable = tsin_stock_index }",
          "\t\tset_variable = { name = tsin_stock_index value = tsin_stock_index_value }", "\t}", "}", ""]
    e += ["tsin_dissolve_all_companies_effect = {"]
    for c, *_ in COMPANIES:
        e += [f"\tif = {{ limit = {{ has_country_modifier = tsin_company_{c} }} remove_country_modifier = tsin_company_{c} }}",
              f"\tremove_variable = tsin_hq_{c}", f"\tremove_variable = tsin_stock_{c}"]
    e += ["\tif = {", "\t\tlimit = { has_variable = tsin_charter_colonial }",
          "\t\tremove_variable = tsin_charter_colonial", "\t\tremove_country_modifier = tsin_charter_colonial_company",
          "\t}", "\ttsin_revoke_company_charters_effect = yes", "\tremove_variable = tsin_has_stock_market",
          "\tremove_variable = tsin_stock_index", "\tremove_variable = tsin_chairman"]
    e += [f"\tremove_variable = tsin_index_h{i}" for i in range(HISTORY)]
    e += ["}", ""]
    e += [f"# Shifts the index history h0 (newest) .. h{HISTORY - 1} (oldest).",
          "tsin_shift_stock_history_effect = {"]
    for i in range(HISTORY - 1, 0, -1):
        e += ["\tif = {", f"\t\tlimit = {{ has_variable = tsin_index_h{i - 1} }}",
              f"\t\tset_variable = {{ name = tsin_index_h{i} value = var:tsin_index_h{i - 1} }}", "\t}"]
    e += ["\tset_variable = { name = tsin_index_h0 value = var:tsin_stock_index }", "}", ""]
    return "\n".join(e)


def decisions() -> str:
    parts = [HEADER + "# Industrial companies: permanent output modifiers with upkeep, limited by tsin_company_limit.", ""]
    for c, adv, image, _, _ in COMPANIES:
        parts.append(FOUND.format(c=c, adv=adv, image=image))
    parts.append(DISSOLVE)
    return "\n".join(parts)


def main() -> None:
    OUT_DECISIONS.write_text(decisions(), encoding="utf-8-sig")
    OUT_VALUES.write_text(values(), encoding="utf-8-sig")
    OUT_EFFECTS.write_text(effects(), encoding="utf-8-sig")
    for p in (OUT_DECISIONS, OUT_VALUES, OUT_EFFECTS):
        print("wrote", p.relative_to(ROOT))


if __name__ == "__main__":
    main()
