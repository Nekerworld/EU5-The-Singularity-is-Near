"""Generate in_game/common/decisions/tsin_company_decisions.txt (one found decision per company plus one dissolve decision)."""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "in_game/common/decisions/tsin_company_decisions.txt"

# company key suffix, required advance, illustration good
COMPANIES = [
    ("steel", "tsin_bessemer_process_advance", "steel"),
    ("machinery", "tsin_machine_works_advance", "tsin_engines"),
    ("textile", "tsin_mechanized_textile_mill_advance", "cloth"),
    ("chemical", "tsin_improved_fertilizer_advance", "tsin_fertilizer"),
    ("railway", "tsin_railway_network_advance", "steel"),
]

FOUND = """tsin_found_{c}_company_decision = {{
	decision_category = economy_decisions
	image = "gfx/interface/icons/trade_goods/illustrations/icon_goods_{good}.dds"

	potential = {{
		has_advance = {adv}
		NOT = {{ has_country_modifier = tsin_company_{c} }}
	}}

	allow = {{
		tsin_company_count < tsin_company_limit
		gold >= tsin_gold_cost_4
	}}

	ai_will_do = {{
		value = 50
	}}

	option = {{
		name = tsin_found_{c}_company_decision.a
		ai_chance = {{ value = 100 }}
		effect = {{
			change_gold_effect = {{ scale = -4 }}
			add_country_modifier = {{ modifier = tsin_company_{c} months = -1 }}
		}}
	}}
}}
"""

DISSOLVE_HEAD = """tsin_dissolve_companies_decision = {
	decision_category = economy_decisions
	image = "gfx/interface/icons/trade_goods/illustrations/icon_goods_steel.dds"

	potential = {
		tsin_company_count > 0
	}

	allow = {
		always = yes
	}

	ai_will_do = {
		value = 0
	}

	option = {
		name = tsin_dissolve_companies_decision.a
		ai_chance = { value = 100 }
		effect = {
"""


def main() -> None:
    parts = [
        "# Generated by tools/gen_company_decisions.py - edit the generator, not this file.",
        "# Industrial companies: permanent output modifiers with upkeep, limited by tsin_company_limit.",
        "",
    ]
    for c, adv, good in COMPANIES:
        parts.append(FOUND.format(c=c, adv=adv, good=good))
    body = DISSOLVE_HEAD
    for c, _, _ in COMPANIES:
        body += f"\t\t\tif = {{ limit = {{ has_country_modifier = tsin_company_{c} }} remove_country_modifier = tsin_company_{c} }}\n"
    body += "\t\t}\n\t}\n}\n"
    parts.append(body)
    OUT.write_text("\n".join(parts), encoding="utf-8-sig")
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
