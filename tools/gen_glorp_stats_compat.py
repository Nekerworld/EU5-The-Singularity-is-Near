"""Generate local-only Glorp overrides; never vendor workshop sources into TSIN."""
from pathlib import Path
import argparse
import pdx

GLORP_REL = 'in_game/gui/glorp.gui'
LEFT_REL = 'in_game/gui/panels/left_panel/glorpUI_left_panel.gui'


def patched_files(source: Path) -> dict[str, str]:
    text = pdx.read_text(source / GLORP_REL)
    anchor = '                        expand = {}\n                    }\n                }\n\n                ### CORNER2'
    assert text.count(anchor) == 1, 'Glorp stats layout changed; review integration before regenerating'
    text = text.replace(anchor, '                        tsin_glorp_stats_rows = {}\n' + anchor)
    for old, new in [('size = { 450 90 }', 'size = { 450 150 }'),
                     ('maximumsize = { 515 90 }', 'maximumsize = { 515 150 }'),
                     ('size = { 515 90 }', 'size = { 515 150 }')]:
        assert text.count(old) == 1, old
        text = text.replace(old, new)
    # Keep the expand/collapse ribbon below the expanded stats bar.
    text = text.replace('position = { 20 213 }', 'position = { 20 273 }')
    left = pdx.read_text(source / LEFT_REL)
    assert left.count('position = { 20 213 }') == 1
    left = left.replace('position = { 20 213 }', 'position = { 20 273 }')
    note = '# LOCAL ONLY: Glorp UI + TSIN stats. Generated by TSIN tools/gen_glorp_stats_compat.py.\n'
    return {GLORP_REL: note + text, LEFT_REL: note + left}


def generate(source: Path, output: Path) -> dict[str, str]:
    files = patched_files(source)  # Validate all anchors before writing either file.
    for rel, text in files.items():
        pdx.write_text_bom(output / rel, text)
    return files


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=pdx.workshop_root() / '3812518640')
    parser.add_argument('--output', type=Path, default=pdx.MOD_ROOT.parent / 'The Singularity Is Near - Playset Compat')
    args = parser.parse_args()
    for rel in generate(args.source, args.output):
        print(rel)
