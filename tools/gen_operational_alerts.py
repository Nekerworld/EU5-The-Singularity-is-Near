def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    data=json.loads(pdx.read_text(pdx.MOD_ROOT/REGISTRY));output=build(data);bad=[]
    for rel,text in output.items():
        p=pdx.MOD_ROOT/rel
        if args.check:
            if not p.exists() or pdx.read_text(p)!=text:bad.append(rel)
        else:pdx.write_text_bom(p,text)
    for p in bad:print('OUTDATED',p)
    print(f'{len(output)} operational files; {len(bad)} mismatches')
    return bool(bad)

if __name__=='__main__':raise SystemExit(main())
