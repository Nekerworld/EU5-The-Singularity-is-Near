def validate(data):
    ids=[r['id'] for r in data['rules']]
    if len(ids)!=len(set(ids)) or any(not re.fullmatch(r'[a-z][a-z0-9_]*',id) for id in ids):raise ValueError('Invalid/duplicate rule ID')
    if any(r['severity'] not in ['critical','attention'] for r in data['rules']):raise ValueError('Invalid severity')
    for r in data['rules']:
        if set(r['title'])!={'english','korean'} or set(r['detail'])!={'english','korean'}:raise ValueError('Missing localization')
        if re.search(r'has_active_disaster|is_situation_active',r['condition']):raise ValueError('Situations and disasters belong to the existing ribbon')
        if re.search(r'any_country|every_country|every_owned_location|any_owned_location',r['condition']):raise ValueError('UI predicates must be cheap')
    if not 1<=data['scan_months']<=12:raise ValueError('Invalid scan interval')
    return sorted(data['rules'],key=lambda r:(r['severity']!='critical',ids.index(r['id'])))


