def jr(field,key='scope:tsin_annex_target'):
    return f'"global_variable_map(tsin_succession_{field}|{key})"'


def jw(field,value,key='scope:tsin_annex_target'):
    return f'add_to_global_variable_map = {{ name = tsin_succession_{field} key = {key} value = {value} }}'


