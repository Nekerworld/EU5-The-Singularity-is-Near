"""Generate the bill proposal events (docs/legislation.md).

tsin_legislation.100 picks a category; .110 .. .170 list the policies of that category's laws. Each option
copies the policy's own potential and allow (without the bill lock) so only policies that could be enacted
are offered, and tables the policy with tsin_table_bill_effect.

Laws are read from the mod (in_game/common/laws/tsin_*_laws.txt) and the installed game (vanilla laws).
Re-run after changing a bill law or after a game patch:  python tools/gen_bill_events.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pdx  # noqa: E402

OUT = pdx.MOD_ROOT / "in_game" / "events" / "tsin_legislation_bills.txt"

# event id -> (comment, laws)
CATEGORIES = [
    (110, "Labour and welfare", ["tsin_labor_law", "tsin_welfare_law"]),
    (120, "Taxation, money and association", ["tsin_taxation_law", "tsin_monetary_standard_law", "tsin_assembly_law"]),
    (130, "Land and church", ["tsin_land_reform_law", "tsin_frontier_land_law", "tsin_church_state_law"]),
    (140, "Industry and trusts", ["tsin_industrial_investment_law", "tsin_trust_law", "tsin_environment_law"]),
    (150, "Slavery", ["tsin_slave_trade_law", "slavery_laws"]),
    (160, "Press and immigration", ["press_law", "immigration_law"]),
    (170, "Popular education", ["education_masses_law"]),
]
VANILLA_LAW_FILE = "in_game/common/laws/01_common.txt"
ESTATES = ["nobles_estate", "clergy_estate", "burghers_estate", "peasants_estate", "crown_estate"]
LOCK = "tsin_policy_enactable_trigger = yes"


def blocks(text: str) -> dict[str, str]:
    return {b.key: b.text for b in pdx.top_level_blocks(text)}


def inner(block: str) -> str:
    """Body of `key = { ... }` without the outer braces."""
    return block[block.index("{") + 1:block.rindex("}")]


def law_policies(law_text: str) -> list[tuple[str, str, str]]:
    """[(policy, potential body, allow body)] of a law block."""
    out = []
    for key, text in blocks(inner(law_text)).items():
        if key in ("potential", "allow"):
            continue
        sub = blocks(inner(text))
        pot = inner(sub["potential"]) if "potential" in sub else ""
        allow = inner(sub["allow"]) if "allow" in sub else ""
        allow = re.sub(r"\btsin_policy_enactable_trigger\s*=\s*yes\b", "", allow)
        out.append((key, pot, allow))
    return out


def reindent(body: str, tabs: int) -> list[str]:
    lines = [l.strip() for l in pdx.strip_comments(body).split("\n")]
    out, depth = [], 0
    for l in lines:
        if not l:
            continue
        lead = 1 if l.startswith("}") else 0
        depth -= lead
        out.append("\t" * (tabs + depth) + l)
        depth += l.count("{") - (l.count("}") - lead)
    return out


def option(policy: str, pot: str, allow: str) -> list[str]:
    o = ["\toption = {", f"\t\tname = {policy}", "\t\ttrigger = {",
         f"\t\t\tany_possible_policy = {{ this = policy:{policy} }}",
         f"\t\t\tNOT = {{ has_policy = policy:{policy} }}"]
    o += reindent(pot, 3) + reindent(allow, 3)
    o += ["\t\t}", f"\t\ttsin_table_bill_effect = {{ POLICY = policy:{policy} BONUS = 0 }}",
          "\t\tai_chance = {", "\t\t\tfactor = 5"]
    for e in ESTATES:
        o += ["\t\t\tmodifier = {", "\t\t\t\tadd = 10",
              f"\t\t\t\tpolicy:{policy} = {{ any_estate_type_preferring = {{ this = estate_type:{e} }} }}",
              f"\t\t\t\t\"estate_power(estate_type:{e})\" >= 0.25", "\t\t\t}"]
    o += ["\t\t\tmodifier = {", "\t\t\t\tadd = 10",
          f"\t\t\t\tpolicy:{policy} = {{ tsin_bill_reform_policy_trigger = yes }}",
          "\t\t\t\ttsin_bill_reform_pressure_trigger = yes", "\t\t\t}",
          "\t\t}", "\t}", ""]
    return o


def main() -> int:
    game = pdx.game_root()
    laws: dict[str, str] = {}
    for p in sorted((pdx.MOD_ROOT / "in_game/common/laws").glob("tsin_*_laws.txt")):
        laws.update(blocks(pdx.read_text(p)))
    laws.update({k: v for k, v in blocks(pdx.read_text(game / VANILLA_LAW_FILE)).items() if k not in laws})

    lines = [
        "# GENERATED by tools/gen_bill_events.py from the bill laws (mod tsin_*_laws.txt, vanilla 01_common.txt).",
        "# Do not edit by hand; re-run the generator after changing a bill law or after a game patch.",
        "",
        "namespace = tsin_legislation",
        "",
        "# Choose the field of the bill",
        "tsin_legislation.100 = {",
        "\ttype = country_event", "\toutcome = neutral",
        "\ttitle = tsin_legislation.100.title",
        "\tdesc = tsin_legislation.100.desc",
        "\tillustration_tags = {", "\t\t10 = interior", "\t\t10 = regular", "\t}",
        "",
    ]
    for eid, _, law_keys in CATEGORIES:
        cond = " ".join(f"this = law:{k}" for k in law_keys)
        lines += ["\toption = {", f"\t\tname = tsin_legislation.100.c{eid}",
                  "\t\ttrigger = {", f"\t\t\tany_possible_policy = {{ law = {{ OR = {{ {cond} }} }} }}", "\t\t}",
                  f"\t\ttrigger_event_non_silently = tsin_legislation.{eid}",
                  "\t\tai_chance = {", "\t\t\tfactor = 10", "\t\t}", "\t}", ""]
    lines += ["\toption = {", "\t\tname = tsin_legislation.100.z", "\t\tai_chance = {", "\t\t\tfactor = 1",
              "\t\t}", "\t}", "}", ""]

    count = 0
    for eid, comment, law_keys in CATEGORIES:
        lines += [f"# {comment}", f"tsin_legislation.{eid} = {{", "\ttype = country_event", "\toutcome = neutral",
                  f"\ttitle = tsin_legislation.{eid}.title", f"\tdesc = tsin_legislation.{eid}.desc",
                  "\tillustration_tags = {", "\t\t10 = interior", "\t\t10 = regular", "\t}", ""]
        for law in law_keys:
            if law not in laws:
                print(f"law not found: {law}")
                return 1
            for pol, pot, allow in law_policies(laws[law]):
                lines += option(pol, pot, allow)
                count += 1
        lines += ["\toption = {", f"\t\tname = tsin_legislation.{eid}.z", "\t\tai_chance = {", "\t\t\tfactor = 1",
                  "\t\t}", "\t}", "}", ""]
    pdx.write_text_bom(OUT, "\n".join(lines))
    print(f"bill options: {count}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
