"""Generate historical-role diagnostics without changing land, cash or native HEX state."""
from pathlib import Path
import argparse
import json
import pdx


def build():
    data = json.loads((pdx.MOD_ROOT / 'data/historical_progression.json').read_text(encoding='utf-8'))
    cores = data['russia']['protected_locations']
    if len(cores) != len(set(cores)) or 'moscow' not in cores:
        raise ValueError('invalid Russia protection set')
    core_guards = '\n'.join(f'location:{loc} = {{ OR = {{ owner ?= {{ tsin_history_human_realm = yes }} controller ?= {{ tsin_history_human_realm = yes }} }} }}' for loc in cores)
    core_ids = '\n'.join('this = location:' + loc for loc in cores)
    triggers = f'''# GENERATED by tools/gen_historical_progression.py.
tsin_history_human_realm = {{
    OR = {{ is_ai = no top_overlord ?= {{ is_ai = no }} }}
}}
tsin_history_ai_realm = {{ is_ai = yes NOT = {{ tsin_history_human_realm = yes }} }}
tsin_history_russia_player_blocked = {{ OR = {{
{core_guards}
}} }}
# Diagnostic shortlist only, not proof that a location is safe or profitable to sell.
tsin_history_border_shortlist = {{
    is_ownable = yes
    exists = owner
    owner = {{ tsin_history_ai_realm = yes at_war = no num_locations > 1 }}
    controller = owner
    is_capital = no
    is_historical_capital = no
    is_port = no
    is_market_center = no
    location_rank = location_rank:rural_settlement
    NOT = {{ is_connected_to = owner.capital }}
    NOT = {{ OR = {{
{core_ids}
    }} }}
    NOT = {{ OR = {{ raw_material = goods:goods_gold raw_material = goods:iron raw_material = goods:copper raw_material = goods:coal }} }}
}}
'''
    effects = '''# GENERATED. Manual diagnostics, at most once per reviewer per game year.
tsin_history_review_effect = {
    save_scope_as = tsin_history_reviewer
    set_variable = { name = tsin_history_review_countries value = 0 }
    set_variable = { name = tsin_history_review_hex value = 0 }
    set_variable = { name = tsin_history_review_border value = 0 }
    set_variable = { name = tsin_history_review_russia_blocked value = 0 }
    if = {
        limit = { tsin_history_russia_player_blocked = yes }
        set_variable = { name = tsin_history_review_russia_blocked value = 1 }
    }
    every_country = {
        limit = { tsin_history_ai_realm = yes }
        scope:tsin_history_reviewer = { change_variable = { name = tsin_history_review_countries add = 1 } }
        if = {
            limit = { has_variable = hex_key }
            scope:tsin_history_reviewer = { change_variable = { name = tsin_history_review_hex add = 1 } }
        }
        if = { limit = { has_variable = tsin_history_border_sample } remove_variable = tsin_history_border_sample }
        if = {
            limit = { any_owned_location = { tsin_history_border_shortlist = yes } }
            save_scope_as = tsin_history_review_owner
            random_owned_location = {
                limit = { tsin_history_border_shortlist = yes }
                scope:tsin_history_review_owner = { set_variable = { name = tsin_history_border_sample value = prev years = 1 } }
            }
            scope:tsin_history_reviewer = { change_variable = { name = tsin_history_review_border add = 1 } }
        }
    }
    set_variable = { name = tsin_history_review_cooldown years = 1 }
    debug_log = tsin_history_review_log
}
'''
    decisions = '''tsin_history_review_decision = {
    decision_category = other_decisions
    potential = { is_ai = no }
    allow = { NOT = { has_variable = tsin_history_review_cooldown } }
    ai_will_do = { value = 0 }
    option = {
        name = tsin_history_review_decision.a
        effect = {
            tsin_history_review_effect = yes
            trigger_event_non_silently = tsin_history_review.1
        }
    }
}
'''
    events = '''namespace = tsin_history_review
tsin_history_review.1 = {
    type = country_event
    title = tsin_history_review.1.title
    desc = tsin_history_review.1.desc
    outcome = neutral
    illustration_tags = { 10 = interior 10 = regular }
    option = { name = tsin_history_review.1.a }
}
'''
    en = {
        'tsin_history_review_decision.title': 'Review historical progression and borders',
        'tsin_history_review_decision.desc': 'Inspect AI realms, saved HEX role markers and a conservative shortlist of isolated rural land. This review never transfers land or money. Repeat after one year.',
        'tsin_history_review_decision.a': 'Prepare the review.',
        'tsin_history_review.1.title': 'Historical progression review',
        'tsin_history_review.1.desc': "AI realms: [ROOT.GetCountry.MakeScope.GetVariable('tsin_history_review_countries').GetValue|0]\nWith saved HEX role markers: [ROOT.GetCountry.MakeScope.GetVariable('tsin_history_review_hex').GetValue|0]\nRealms with an isolated rural shortlist sample: [ROOT.GetCountry.MakeScope.GetVariable('tsin_history_review_border').GetValue|0]\nRussia blocked by human ownership or control of a protected city (1=yes): [ROOT.GetCountry.MakeScope.GetVariable('tsin_history_review_russia_blocked').GetValue|0]\n\nA saved HEX marker does not prove the mod is currently enabled. Shortlist samples exclude capitals, ports, market centres and selected mining resources but still need strategic review. No land, cash, armies or HEX state changed.",
        'tsin_history_review.1.a': 'File the report.',
        'tsin_history_review_log': "TSIN_HISTORY_REVIEW [ROOT.GetCountry.GetName] AI=[ROOT.GetCountry.MakeScope.GetVariable('tsin_history_review_countries').GetValue|0] HEX_MARKERS=[ROOT.GetCountry.MakeScope.GetVariable('tsin_history_review_hex').GetValue|0] BORDER_REALMS=[ROOT.GetCountry.MakeScope.GetVariable('tsin_history_review_border').GetValue|0] RUSSIA_HUMAN_BLOCK=[ROOT.GetCountry.MakeScope.GetVariable('tsin_history_review_russia_blocked').GetValue|0]",
    }
    ko = {
        'tsin_history_review_decision.title': '역사 진행·국경 점검',
        'tsin_history_review_decision.desc': 'AI 세력권·저장된 HEX 역할 표식·고립 농촌 영토의 보수적인 예비 목록을 점검합니다. 영토·자금을 이전하지 않습니다. 1년 후 다시 점검할 수 있습니다.',
        'tsin_history_review_decision.a': '점검 보고서를 작성하라.',
        'tsin_history_review.1.title': '역사 진행·국경 점검 보고',
        'tsin_history_review.1.desc': "AI 세력권: [ROOT.GetCountry.MakeScope.GetVariable('tsin_history_review_countries').GetValue|0]\nHEX 역할 표식 보유국: [ROOT.GetCountry.MakeScope.GetVariable('tsin_history_review_hex').GetValue|0]\n고립 농촌 영토 예비 후보 보유국: [ROOT.GetCountry.MakeScope.GetVariable('tsin_history_review_border').GetValue|0]\n러시아 보호 도시의 인간 소유·점령 차단 (1=차단): [ROOT.GetCountry.MakeScope.GetVariable('tsin_history_review_russia_blocked').GetValue|0]\n\n저장된 HEX 표식은 해당 모드의 현재 활성 여부를 보장하지 않습니다. 예비 후보에서 수도·항구·시장 중심·일부 광물은 제외했지만 전략적 중요도는 추가 확인이 필요합니다. 영토·자금·군대·HEX 상태는 변경하지 않았습니다.",
        'tsin_history_review.1.a': '보고서를 보관하라.',
        'tsin_history_review_log': en['tsin_history_review_log'].replace('TSIN_HISTORY_REVIEW ', 'TSIN_HISTORY_REVIEW [역사점검] '),
    }
    files = {
        'in_game/common/scripted_triggers/tsin_historical_progression_triggers.txt': triggers,
        'in_game/common/scripted_effects/tsin_historical_progression_effects.txt': effects,
        'in_game/common/decisions/tsin_history_review_decisions.txt': decisions,
        'in_game/events/tsin_history_review.txt': events,
    }
    for lang, entries in [('english', en), ('korean', ko)]:
        files[f'main_menu/localization/{lang}/tsin_history_review_l_{lang}.yml'] = 'l_' + lang + ':\n' + '\n'.join(' '+key+': '+json.dumps(value, ensure_ascii=False) for key, value in entries.items()) + '\n'
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bad = []
    for rel, body in build().items():
        path = pdx.MOD_ROOT / rel
        if args.check:
            if not path.exists() or pdx.read_text(path) != body:
                bad.append(rel)
        else:
            pdx.write_text_bom(path, body)
    print(f'Historical progression: {len(bad)} mismatches')
    for rel in bad: print(rel)
    return bool(bad)


if __name__ == '__main__':
    raise SystemExit(main())
