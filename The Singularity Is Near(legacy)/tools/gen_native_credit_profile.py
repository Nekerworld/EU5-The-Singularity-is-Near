"""Read-only monthly native government debt profile; no contract/cash mutations."""
import argparse
import pdx

EFFECT = """tsin_native_credit_profile_effect = {
 save_scope_as = tsin_credit_report_country
 set_variable = { name = tsin_native_bond_principal value = 0 }
 set_variable = { name = tsin_native_due_12 value = 0 }
 set_variable = { name = tsin_native_due_now value = 0 }
 set_variable = { name = tsin_native_tax_trade_annual value = { value = monthly_income_trade_and_tax multiply = 12 min = 0 } }
 remove_variable = tsin_native_debt_income_ratio
 if = {
  limit = { var:tsin_native_tax_trade_annual > 0 }
  set_variable = { name = tsin_native_debt_income_ratio value = { value = total_debt divide = var:tsin_native_tax_trade_annual multiply = 100 } }
 }
 if = {
  limit = { total_debt > 0 }
  every_loan = {
   limit = { borrower ?= scope:tsin_credit_report_country remaining_debt > 0 }
   if = {
    limit = { is_bond = yes }
    scope:tsin_credit_report_country = { change_variable = { name = tsin_native_bond_principal add = prev.remaining_debt } }
   }
   else = {
    if = {
     limit = { months_left <= 0 }
     scope:tsin_credit_report_country = { change_variable = { name = tsin_native_due_now add = prev.remaining_debt } }
    }
    else = {
     if = {
      limit = { months_left <= 12 }
      scope:tsin_credit_report_country = { change_variable = { name = tsin_native_due_12 add = prev.remaining_debt } }
     }
    }
   }
  }
 }
 set_variable = tsin_native_credit_sampled
}
"""

def build():
    return {
      'in_game/common/scripted_effects/tsin_native_credit_profile_effects.txt': '# GENERATED by tools/gen_native_credit_profile.py\n'+EFFECT,
      'in_game/common/on_action/tsin_native_credit_profile.txt': """# GENERATED by tools/gen_native_credit_profile.py
monthly_country_pulse = { on_actions = { tsin_native_credit_profile_monthly } }
tsin_native_credit_profile_monthly = {
 trigger = { is_ai = no num_locations > 0 }
 effect = { tsin_native_credit_profile_effect = yes }
}
"""}

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args=parser.parse_args()
    bad=[]
    for rel, text in build().items():
        path=pdx.MOD_ROOT/rel
        if args.check:
            if not path.exists() or pdx.read_text(path)!=text: bad.append(rel)
        else: pdx.write_text_bom(path,text)
    print(f'Native credit profile: {len(bad)} mismatches')
    for rel in bad: print(rel)
    return bool(bad)

if __name__=='__main__': raise SystemExit(main())
