def patch_decisions(text: str) -> str:
    marker = 'TSIN: ages 7+ browser'
    if marker in text:
        raise ValueError('decisions CONTENT ages already patched')
    anchor = '\t\t\t\t\t\t\t\tvbox = {\n\t\t\t\t\t\t\t\t\tusing = layoutpolicy_expanding\n\t\n\t\t\t\t\t\t\t\t\tfiltered_sorted_list = {'
    if text.count(anchor) != 1:
        # Fall back: find filtered_sorted_list under content subtab
        needle = 'datacontext = "[DecisionsLateralView.GetUniqueContentCategoriesSortSearch]"'
        if text.count(needle) != 1:
            raise ValueError('CONTENT unique list anchor not found')
        idx = text.index(needle)
        # Insert before the filtered_sorted_list that contains this datacontext
        list_start = text.rfind('filtered_sorted_list = {', 0, idx)
        if list_start < 0:
            raise ValueError('filtered_sorted_list before unique content not found')
        # Find start of owning vbox line with using = layoutpolicy_expanding just above
        vbox_start = text.rfind('vbox = {', 0, list_start)
        # Insert after the expanding vbox opens — after its first property line
        insert_at = text.find('\n', text.find('using = layoutpolicy_expanding', vbox_start)) + 1
        return text[:insert_at] + CONTENT_AGES_BLOCK + text[insert_at:]
    return text.replace(anchor, CONTENT_AGES_BLOCK + anchor, 1)


def patch_technology(text: str) -> str:
    if 'TSIN: age tabs fill' in text or 'TSIN: scrollable age tabs' in text:
        raise ValueError('technology age tabs already patched')
    start = text.find('header_secondary_tabs = {\n\t\t\t\t\tvisible = "[IsPlayerValid]"')
    if start < 0:
        raise ValueError('technology age header_secondary_tabs not found')
    # Find the matching closing of header_secondary_tabs
    brace = text.index('{', start)
    end = pdx.matching_brace(pdx.strip_comments(text), brace)
    # end points at closing }; include through newline after }
    close = end + 1
    while close < len(text) and text[close] in ' \t':
        close += 1
    if close < len(text) and text[close] == '\n':
        close += 1
    return text[:start] + TECH_AGE_TABS.lstrip('\n') + text[close:]


def patch_advances(text: str) -> str:
    old = 'visible = "[Not(IsDataModelEmpty(AdvancesLateralView.GetUniqueAdvancesForAge(Age.Self)))]"'
    new = (
        'visible = "[Or('
        + AGE7_PLUS
        + ', Not(IsDataModelEmpty(AdvancesLateralView.GetUniqueAdvancesForAge(Age.Self))))]"'
    )
    if text.count(old) != 1:
        if text.count(new) == 1:
            raise ValueError('advances unique-by-age visibility already patched')
        raise ValueError('unique-by-age visibility anchor not found or ambiguous')
    return text.replace(old, new, 1)


def build(game=None) -> dict[str, str]:
    game = game or pdx.game_root()
    result = {
        DECISIONS: NOTE + patch_decisions(pdx.read_text(game / DECISIONS)),
        TECHNOLOGY: NOTE + patch_technology(pdx.read_text(game / TECHNOLOGY)),
        ADVANCES: NOTE + patch_advances(pdx.read_text(game / ADVANCES)),
    }
    # Drop obsolete filler localization if regenerating over an older checkout.
    for lang in ('english', 'korean'):
        result[f'main_menu/localization/{lang}/tsin_content_ages_l_{lang}.yml'] = f'l_{lang}:\n'
    return {rel: '\n'.join(line.rstrip() for line in text.splitlines()) + '\n' for rel, text in result.items()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = build()
    bad = []
    for rel, text in files.items():
        path = pdx.MOD_ROOT / rel
        if args.check:
            if not path.exists() or pdx.read_text(path) != text:
                bad.append(rel)
        else:
            pdx.write_text_bom(path, text)
    print(f'{len(files)} content-age UI files; {len(bad)} mismatches')
    for name in bad:
        print(name)
    return 1 if bad else 0


if __name__ == '__main__':
    raise SystemExit(main())
