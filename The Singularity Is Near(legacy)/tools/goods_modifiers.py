"""Generate per-good modifier types and icons for every mod good, mirroring a vanilla template good.

Vanilla defines ten modifier types per good (can_extract_X, ban_exports_of_X, ...).
Usage:
  python tools/goods_modifiers.py            # rewrite the mod files for all goods in tsin_goods.txt
  python tools/goods_modifiers.py steel X    # print the blocks for one good
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pdx  # noqa: E402

COMMON = pdx.game_root() / "main_menu/common"
TEMPLATE = "steel"
GOODS_FILE = pdx.MOD_ROOT / "in_game/common/goods/tsin_goods.txt"
OUT_TYPES = pdx.MOD_ROOT / "main_menu/common/modifier_type_definitions/tsin_goods_modifier_types.txt"
OUT_ICONS = pdx.MOD_ROOT / "main_menu/common/modifier_icons/tsin_goods_modifier_icons.txt"
SOURCES = {
    "types": "modifier_type_definitions/00_modifier_types.txt",
    "icons": "modifier_icons/00_modifier_icons.txt",
}


def blocks_for(kind: str, template: str, new: str) -> list[str]:
    text = pdx.strip_comments(pdx.read_text(COMMON / SOURCES[kind]))
    out = []
    for b in pdx.top_level_blocks(text):
        if re.search(rf"(^|_){template}(_|$)", b.key):
            out.append(re.sub(rf"(?<![a-z]){template}(?![a-z])", new, b.text))
    return out


def main() -> int:
    if len(sys.argv) == 3:
        template, new = sys.argv[1], sys.argv[2]
        for kind in SOURCES:
            print(f"# ---- {kind}")
            print("\n\n".join(blocks_for(kind, template, new)))
        return 0
    goods = [b.key for b in pdx.top_level_blocks(pdx.read_text(GOODS_FILE))]
    for kind, path in (("types", OUT_TYPES), ("icons", OUT_ICONS)):
        parts = [f"# Generated by tools/goods_modifiers.py from vanilla '{TEMPLATE}'. Goods: {', '.join(goods)}."]
        for good in goods:
            parts.append(f"# {good}")
            parts.extend(blocks_for(kind, TEMPLATE, good))
        pdx.write_text_bom(path, "\n\n".join(parts) + "\n")
        print(f"wrote {path.relative_to(pdx.MOD_ROOT)} ({len(goods)} goods)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
